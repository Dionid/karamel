#!/usr/bin/env python3
"""Text-analysis half of the harness linter — see lint.sh, which drives it.

Everything here reads Markdown and the frontmatter of skills. It is a separate
file from lint.sh because these checks are string work — GitHub heading slugs,
fenced-code extraction, frontmatter parsing — and doing them in bash produces
the kind of quoting that the linter exists to prevent.

Two severities. `error` fails the run; `warn` is reported and does not, because
some of the rules it enforces are written in the docs as approximations ("keep
SKILL.md under ~200 lines") and a tilde must not turn into a red pipeline on the
day it is wired up. `--strict` promotes warnings to errors.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

def _find_root() -> Path:
    """Find the generated marker or the tracked source manifest."""
    for d in Path(__file__).resolve().parents:
        if (d / "harness.json").is_file() or (d / "workspace.json").is_file():
            return d
    sys.exit("cannot locate the workspace root (harness.json / workspace.json)")


ROOT = _find_root()
# .claude/ is generated by the repo-local builder from agents/.
# Checks that read it are skipped when it is absent rather than failing: a fresh
# clone has not been bootstrapped yet.
CLAUDE = ROOT / ".claude"

# The same skills are linked under two names — .claude/ for Claude Code and
# .agents/ for Codex — so a path named in the docs may carry either prefix and
# resolves through the same layers either way.
BUILT_TREES = (".claude/", ".agents/")

# Documented in .claude/skills/writing-skills/SKILL.md ("Token budget").
SKILL_BODY_LINES = 200
# These are attention budgets, not correctness gates. Policy correctness is
# guarded separately by agents-policy.test.py.
AGENTS_LINE_BUDGETS = {
    "AGENTS.md": 400,
}
# The frontmatter description is what decides whether a skill triggers at all;
# past ~1024 chars it is being used as documentation instead of a trigger.
SKILL_DESC_CHARS = 1024

# Claude Code shows the model every skill's name and description under ONE
# character budget: SLASH_COMMAND_TOOL_CHAR_BUDGET from the settings `env`, or
# about 1% of the context window when unset (the docs name 8000 chars as the
# fallback). Past it, descriptions are dropped starting with the least-used
# skills — the skill is still listed by name, but the model no longer knows
# when to reach for it, which reads as "the skill is gone". Crossing the
# budget is therefore an error, not an attention warning: raise the value in
# agents/claude/settings.base.json or shorten descriptions.
#
# The count below is this repository's share: skills plus slash commands.
# Plugin and user-level skills of the runtime spend from the same budget and
# are invisible here, so a green check is necessary, not sufficient.
CLAUDE_SETTINGS = "agents/claude/settings.base.json"
CLAUDE_COMMANDS = "agents/claude/commands"
SKILL_LISTING_BUDGET_ENV = "SLASH_COMMAND_TOOL_CHAR_BUDGET"
SKILL_LISTING_FALLBACK_CHARS = 8000
SKILL_LISTING_WARN_RATIO = 0.85

# Codex reads the AGENTS.md chain only up to project_doc_max_bytes (32 KiB by
# default) and silently drops the tail — the team rules at the end of the
# file. The limit is read from the tracked Codex config so the two cannot
# drift apart; crossing it is a correctness failure, so it is an error.
CODEX_CONFIG = "agents/codex/config.base.toml"
CODEX_PROJECT_DOC_DEFAULT_BYTES = 32 * 1024
AGENTS_BYTES_WARN_RATIO = 0.9

# Paths named in the docs that are deliberately not on disk: they belong to
# another repo, or they are history being explained. Anything not listed here
# has to exist, because AGENTS.md tells agents to call these paths verbatim.
PATH_ALLOWLIST = {
    # Belong to a repo in packages/, not to this one.
    ".claude/commands/opsx/",
    ".claude/skills/openspec-",
    # Explained as the OLD per-repo layout in WORKTREES.md.
    ".claude/worktrees.json",
    # Per-machine and gitignored by design.
    ".claude/settings.local.json",
}

# Command-position patterns that must never appear inside a runnable fence. The
# prose says "never do this" repeatedly — that is why this is checked in fences
# only, and why a naive grep over these docs is 100% false positives.
FORBIDDEN = [
    (re.compile(r"(?:^|[\s;|&])\./wt(?:\s|$)"), "./wt does not exist — call .claude/skills/wt/wt by path"),
    (re.compile(r"(?:^|[\s;|&])\./clone\.sh(?:\s|$)"), "./clone.sh does not exist — call .claude/skills/clone/clone.sh"),
    (re.compile(r"--no-verify|\bcommit\b.*\s-n(?:\s|$)"), "pre-commit hooks are never bypassed"),
    (re.compile(r"git\s+push\b.*(--force|\s-f(?:\s|$))"), "force-push is not done here"),
    (re.compile(r"npm\s+ci\b(?=.*worktrees/)"), "npm ci in a worktree destroys the CoW node_modules — use npm install"),
    (re.compile(r"\bEnterWorktree\b"), "EnterWorktree is banned in this workspace — use .claude/skills/wt/wt"),
    (re.compile(r"docker\s+compose\s+(-f|--file)\s"), "compose is run from the directory owning the file, never with -f from elsewhere"),
]

findings: list[tuple[str, str, str]] = []  # (severity, location, message)


def report(sev: str, loc: str, msg: str) -> None:
    findings.append((sev, loc, msg))


def tracked(*globs: str) -> list[Path]:
    """Files git knows about — so an untracked scratch file is never linted."""
    out = subprocess.run(
        ["git", "-C", str(ROOT), "ls-files", *globs],
        capture_output=True, text=True, check=False,
    ).stdout.split("\n")
    return [ROOT / p for p in out if p]


# ----------------------------------------------------------------- markdown ---

FENCE_RE = re.compile(r"^([ \t]*)```([A-Za-z0-9_-]*)[ \t]*$")


def fences(text: str):
    """Yield (lang, start_line, body) for every fenced block.

    Hand-rolled rather than regex-based because these docs nest fences inside
    list items, and the indentation has to come back with the block for the
    line numbers to point anywhere useful.
    """
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        m = FENCE_RE.match(lines[i])
        if not m:
            i += 1
            continue
        indent, lang = m.group(1), m.group(2)
        body: list[str] = []
        start = i + 1
        i += 1
        while i < len(lines):
            if lines[i].strip() == "```":
                break
            body.append(lines[i][len(indent):] if lines[i].startswith(indent) else lines[i])
            i += 1
        yield lang.lower(), start, body
        i += 1


def slug(heading: str) -> str:
    """GitHub's heading anchor. Underscores and hyphens survive, punctuation does
    not, and an em dash between words therefore leaves a double hyphen."""
    s = heading.strip()
    s = re.sub(r"`([^`]*)`", r"\1", s)          # inline code
    s = re.sub(r"\*\*?([^*]*)\*\*?", r"\1", s)  # emphasis
    s = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", s)  # links
    s = s.lower()
    s = "".join(c for c in s if c.isalnum() or c in " -_")
    return s.strip().replace(" ", "-")


def heading_slugs(text: str) -> set[str]:
    """Every anchor a file offers, including GitHub's -1/-2 duplicate suffixes."""
    seen: dict[str, int] = {}
    out: set[str] = set()
    in_fence = False
    for line in text.split("\n"):
        if FENCE_RE.match(line):
            in_fence = not in_fence
            continue
        if in_fence or not line.startswith("#"):
            continue
        m = re.match(r"^#{1,6}\s+(.*)$", line)
        if not m:
            continue
        base = slug(m.group(1))
        n = seen.get(base, 0)
        out.add(base if n == 0 else f"{base}-{n}")
        seen[base] = n + 1
    return out


def top_segment(path_part: str) -> str:
    """Return the first real segment of a relative link."""
    for part in path_part.split("/"):
        if part not in ("", ".", ".."):
            return part
    return ""


# packages/, worktrees/ and the generated runtime trees are created on
# demand, so whether a link into them resolves depends on the machine. Checked
# when the tree is there (a developer's checkout, where a wrong path is worth
# catching), skipped when it is not (CI, a fresh clone) — otherwise every
# PACKAGES.md link fails in CI for being correct.
def unverifiable(path_part: str) -> bool:
    top = top_segment(path_part)
    if top in (".claude", ".agents", ".codex"):
        return not (ROOT / top).is_dir()
    if top not in ("packages", "worktrees"):
        return False
    root = ROOT / top
    if not root.is_dir():
        return True
    return not any(p.name != ".gitkeep" for p in root.iterdir())


# An OpenSpec archive is frozen by definition: a closed change links to siblings
# that have since moved into the archive themselves, and rewriting those links
# edits the record of what was decided rather than fixing anything. Matched by
# convention, not by a configured path: the archive sits under whatever specRoot
# the manifest names, and the layout below it is OpenSpec's, not a team's.
FROZEN_MARKER = "openspec/changes/archive/"
HARNESS_ARCHIVE_PREFIX = "agents/archive/"


def snapshot_roots() -> tuple[str, ...]:
    """Trees that mirror an external wiki, read from `notion.json`.

    A repository without that manifest has no mirror — silence, not a finding.
    A manifest that exists and cannot be read is a different thing: the scope
    would silently stay wide, and the run would report breakage nobody can fix.

    These are skipped as link SOURCES, never as targets. A `](…)` inside a
    snapshot is an internal address of the system it mirrors
    (`/55bd1a4f…?pvs=25`) — never a file, and any fix survives exactly until the
    next export. A link from a hand-written doc INTO the snapshot is still
    checked, because a break there means the snapshot moved.

    The prefix is returned only for a root whose tree is actually HERE. The
    manifest naming a root and the mirror living in this repository are two
    different facts, and since `knowledge/` moved to its own repository they
    came apart: `notion.json` stays with the harness, the snapshot lands in the
    knowledge repository. Returning a prefix for a tree that is not in this
    checkout would be a narrowing that quietly matches nothing — exactly the
    kind of check that looks like coverage and is not.
    """
    manifest = ROOT / "notion.json"
    if not manifest.is_file():
        return ()
    try:
        roots = json.loads(manifest.read_text())["roots"]
    except Exception as exc:
        report("error", "notion.json",
               f"cannot read snapshot roots, link scope not narrowed: {exc}")
        return ()
    return tuple(
        f"knowledge/references/{name}/"
        for name in roots
        if (ROOT / "knowledge" / "references" / name).is_dir()
    )


def generated_source(f: Path) -> bool:
    """A generated or frozen file whose historical links are not maintained."""
    rel = f.relative_to(ROOT).as_posix()
    return (
        FROZEN_MARKER in rel
        or rel.startswith(HARNESS_ARCHIVE_PREFIX)
        or rel.startswith(snapshot_roots())
    )


def link_severity(_file: Path) -> str:
    """All tracked sources are maintained in this repository."""
    return "error"


def check_links(files: list[Path]) -> None:
    """Relative links resolve, and in-repo anchors point at a real heading."""
    slugs: dict[Path, set[str]] = {}
    for f in files:
        slugs[f] = heading_slugs(f.read_text())

    for f in files:
        if generated_source(f):
            continue
        text = f.read_text()
        for lineno, line in enumerate(text.split("\n"), 1):
            for target in re.findall(r"\]\(([^)\s]+)\)", line):
                if target.startswith(("http://", "https://", "mailto:")):
                    continue
                path_part, _, anchor = target.partition("#")
                if path_part and unverifiable(path_part):
                    continue
                dest = f if not path_part else (f.parent / path_part).resolve()

                if path_part:
                    if not dest.exists():
                        report(link_severity(f), f"{f.relative_to(ROOT)}:{lineno}",
                               f"link target does not exist: {path_part}")
                        continue
                    if dest.is_dir() or dest.suffix != ".md":
                        continue

                if anchor:
                    known = slugs.get(dest)
                    if known is None and dest.suffix == ".md" and dest.exists():
                        known = heading_slugs(dest.read_text())
                        slugs[dest] = known
                    if known is not None and anchor not in known:
                        report(link_severity(f), f"{f.relative_to(ROOT)}:{lineno}",
                               f"anchor has no matching heading: #{anchor}")


# Every directory a built tree can be assembled from, in no particular order —
# a path only has to exist in one of them. Split into facets by which agent
# reads it (common/claude/codex). `agents/` is the one layer a repository laid
# out by `./ops sync` has: all tracked sources land here one-to-one.
LAYER_DIRS = ("agents/common", "agents/claude", "agents/codex")

# `.claude/settings.json` is not a file in any layer: the builder merges it from
# these. Everything else under a built tree is a symlink to a layer file of the
# same relative path.
GENERATED = {".claude/settings.json": ("agents/claude/settings.base.json",)}


def strip_tree(p: str) -> tuple[str, str]:
    """`.claude/skills/wt/wt` → (`.claude`, `skills/wt/wt`). Either built tree
    is stripped to the same remainder, because both are assembled from the same
    layer paths."""
    for tree in BUILT_TREES:
        if p.startswith(tree):
            return tree.rstrip("/"), p[len(tree):]
    return "", p


def in_layers(p: str) -> bool:
    """Does a built-tree path exist — in the tree itself, or in the layer it
    would be assembled from? Both answers count: the built tree is the strongest
    evidence, but CI never has one, and there `agents/` still proves every
    path the engine itself ships."""
    if any((ROOT / g).exists() for g in GENERATED.get(p, ())):
        return True
    tree, rest = strip_tree(p)
    layers = ((tree,) if tree else ()) + LAYER_DIRS
    # `.claude/agents/` is the roles directory. In a layer it is `roles/`; a
    # built tree renames it to `agents/`, because that is where the agents
    # themselves look for it. Without this substitution every mention of
    # `.claude/agents/` in the docs is a false error, and there are enough of
    # them to make the whole check meaningless.
    rests = [rest]
    if rest == "agents" or rest.startswith("agents/"):
        rests.append("roles" + rest[len("agents"):])
    return any((ROOT / layer / r).exists() for layer in layers for r in rests)


def check_paths(files: list[Path]) -> None:
    """`.claude/...` paths named in prose exist — AGENTS.md tells agents to run
    them verbatim, so a renamed script silently becomes an instruction to run
    nothing."""
    # A fresh clone may have no built tree yet. Every generated path is then
    # resolved against `agents/`, the tracked source of truth. Unknown paths are
    # reported once as a warning rather than failing per line; once the layer
    # exists, an unresolved path is a genuine error.
    unresolved: set[str] = set()
    layer_present = CLAUDE.is_dir() or any((ROOT / d).is_dir() for d in LAYER_DIRS)

    for f in files:
        if generated_source(f):
            continue
        for lineno, line in enumerate(f.read_text().split("\n"), 1):
            for raw in re.findall(r"\.(?:claude|agents)/[A-Za-z0-9_./-]+", line):
                p = raw.rstrip(".,:;)`'\"")
                if p in PATH_ALLOWLIST or any(p.startswith(a) for a in PATH_ALLOWLIST):
                    continue
                # Placeholders inside a path are not a path.
                if "<" in p or ">" in p:
                    continue
                if in_layers(p):
                    continue
                if layer_present:
                    report(link_severity(f), f"{f.relative_to(ROOT)}:{lineno}",
                           f"path named in the docs does not exist: {p}")
                else:
                    unresolved.add(p)

    if unresolved:
        report("warn", ".claude",
               f"{len(unresolved)} path(s) not verified — runtime trees are not built "
               "yet, and agents/ does not carry them: " + ", ".join(sorted(unresolved)))


PLACEHOLDER = re.compile(r"<[^>\n]{1,60}>")


def check_fences(files: list[Path]) -> None:
    """Runnable fences parse under `bash -n`.

    Placeholders are substituted first: bash reads `<task>` as a redirect, and
    without this step 23 of 74 fences in this repo "fail" for no reason. A
    `console` fence is prompt-and-output, so only its `$ ` lines are code.
    """
    for f in files:
        for lang, start, body in fences(f.read_text()):
            if lang in ("console", "shell-session"):
                code = [l[2:] for l in body if l.startswith("$ ")]
            elif lang in ("bash", "sh"):
                code = body
            else:
                continue
            if not code:
                continue
            src = PLACEHOLDER.sub("PH", "\n".join(code))
            r = subprocess.run(["bash", "-n"], input=src, capture_output=True, text=True)
            if r.returncode:
                detail = (r.stderr.strip().split("\n") or [""])[0]
                detail = re.sub(r"^bash: line \d+: ", "", detail)
                report("error", f"{f.relative_to(ROOT)}:{start}",
                       f"```{lang} fence does not parse: {detail}")


# A doc that teaches a rule has to be able to show the thing the rule forbids.
# AGENTS.md's compose section does exactly that, with the counter-example marked
# `# WRONG` — so the marker is the escape hatch, and it has to be on the line.
ALLOW_MARKER = re.compile(r"#.*\b(WRONG|НЕЛЬЗЯ|lint:allow)\b")


def check_forbidden(files: list[Path]) -> None:
    """Banned command forms — inside fences only, never in prose."""
    for f in files:
        for lang, start, body in fences(f.read_text()):
            if lang not in ("bash", "sh", "console", "shell-session"):
                continue
            for off, line in enumerate(body):
                code = line[2:] if line.startswith("$ ") else line
                if code.lstrip().startswith("#") or ALLOW_MARKER.search(code):
                    continue
                for pat, msg in FORBIDDEN:
                    if pat.search(code):
                        report("error", f"{f.relative_to(ROOT)}:{start + off}", msg)


# ------------------------------------------------------------------- skills ---

def frontmatter(path: Path) -> dict[str, str] | None:
    lines = path.read_text().split("\n")
    if not lines or lines[0].strip() != "---":
        return None
    fm: dict[str, str] = {}
    for line in lines[1:]:
        if line.strip() == "---":
            return fm
        m = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", line)
        if m:
            fm[m.group(1)] = m.group(2).strip()
    return None


def skill_dirs(root: Path = ROOT) -> list[Path]:
    """Where the skills are: the built tree, or the layers it is built FROM.

    A built tree is a symlink farm over the layer files, so the contract checked
    below — frontmatter name against directory name, a description short enough
    to work as a trigger, a body inside its budget — reads the same either way.
    Requiring `.claude/` meant CI skipped these checks entirely, because a clean
    clone has no built tree and building one needs the engine clone, which is
    not something a product repository's pipeline can be given. A gate that
    quietly checks less than it says is the thing this file exists to prevent.
    """
    built = root / ".claude" / "skills"
    if built.is_dir():
        return [built]
    return [root / d / "skills" for d in LAYER_DIRS if (root / d / "skills").is_dir()]


def role_files() -> list[Path]:
    """Role definitions: `agents/` in a built tree, `roles/` in a layer."""
    built = CLAUDE / "agents"
    if built.is_dir():
        return sorted(built.glob("*.md"))
    out: list[Path] = []
    for d in LAYER_DIRS:
        out += sorted((ROOT / d / "roles").glob("*.md"))
    return out


def skill_listing_budget(root: Path = ROOT) -> int:
    """The character budget Claude Code applies to the skill listing."""
    try:
        env = json.loads((root / CLAUDE_SETTINGS).read_text()).get("env", {})
        value = str(env.get(SKILL_LISTING_BUDGET_ENV, ""))
    except (OSError, ValueError, AttributeError):
        value = ""
    return int(value) if value.isdigit() else SKILL_LISTING_FALLBACK_CHARS


def skill_listing_chars(root: Path = ROOT) -> int:
    """Characters this repository spends on the listing: every skill's and
    slash command's name plus description."""
    total = 0
    for base in skill_dirs(root):
        for d in base.iterdir():
            skill = d / "SKILL.md"
            if not d.is_dir() or not skill.exists():
                continue
            fm = frontmatter(skill) or {}
            total += len(d.name) + len(fm.get("description", ""))
    commands = root / CLAUDE_COMMANDS
    if commands.is_dir():
        for command in commands.glob("*.md"):
            fm = frontmatter(command) or {}
            total += len(command.stem) + len(fm.get("description", ""))
    return total


def check_skill_listing() -> None:
    budget = skill_listing_budget()
    used = skill_listing_chars()
    hint = (f"raise {SKILL_LISTING_BUDGET_ENV} in {CLAUDE_SETTINGS} or shorten descriptions")
    if used > budget:
        report("error", CLAUDE_SETTINGS,
               f"skill listing is {used} chars (skills and commands of this repository alone), over "
               f"the {budget}-char budget — Claude Code drops descriptions of the least-used skills "
               f"past it; {hint}")
    elif used > budget * SKILL_LISTING_WARN_RATIO:
        report("warn", CLAUDE_SETTINGS,
               f"skill listing is {used} chars of the {budget}-char budget — {hint} before it overflows")


def check_skills() -> None:
    roots = skill_dirs()
    if not roots:
        report("warn", "skills", "neither a built tree nor a layer — skill checks skipped")
        return
    check_skill_listing()
    for d in sorted((p for root in roots for p in root.iterdir() if p.is_dir()),
                    key=lambda p: p.name):
        skill = d / "SKILL.md"
        rel = skill.relative_to(ROOT)
        if not skill.exists():
            report("error", str(d.relative_to(ROOT)), "directory has no SKILL.md")
            continue

        fm = frontmatter(skill)
        if fm is None:
            report("error", str(rel), "no YAML frontmatter delimited by --- / ---")
            continue

        if fm.get("name") != d.name:
            report("error", str(rel),
                   f"frontmatter name is {fm.get('name')!r}, directory is {d.name!r} — "
                   "the Skill tool resolves by name, so they must match")

        desc = fm.get("description", "")
        if not desc:
            report("error", str(rel), "frontmatter has no description — the skill will never trigger")
        elif len(desc) > SKILL_DESC_CHARS:
            report("warn", str(rel),
                   f"description is {len(desc)} chars (>{SKILL_DESC_CHARS}) — it is a trigger, not documentation")

        n = len(skill.read_text().split("\n"))
        if n > SKILL_BODY_LINES:
            report("warn", str(rel),
                   f"{n} lines (budget ~{SKILL_BODY_LINES}) — move detail into a sibling file the body links to")

    for agent in role_files():
        fm = frontmatter(agent)
        rel = agent.relative_to(ROOT)
        if fm is None:
            report("error", str(rel), "agent definition has no frontmatter")
            continue
        for key in ("name", "description"):
            if not fm.get(key):
                report("error", str(rel), f"agent frontmatter has no {key}")
        if fm.get("name") and fm["name"] != agent.stem:
            report("error", str(rel), f"frontmatter name {fm['name']!r} != filename {agent.stem!r}")


# ---------------------------------------------------------------- cross-doc ---

def agent_budget_violations(root: Path = ROOT) -> list[tuple[str, int, int]]:
    """Return (path, actual lines, budget) for oversized always-loaded files."""
    violations = []
    for rel, budget in AGENTS_LINE_BUDGETS.items():
        path = root / rel
        if not path.is_file():
            continue
        lines = len(path.read_text().splitlines())
        if lines > budget:
            violations.append((rel, lines, budget))
    return violations

def codex_project_doc_limit(root: Path = ROOT) -> int:
    """project_doc_max_bytes from the tracked Codex config, or Codex's own default."""
    path = root / CODEX_CONFIG
    if path.is_file():
        # Only the top-level section counts: after the first table header the
        # same line belongs to that table, and Codex ignores it there.
        top_level = re.split(r"^\s*\[", path.read_text(), maxsplit=1, flags=re.M)[0]
        m = re.search(r"^\s*project_doc_max_bytes\s*=\s*(\d+)", top_level, re.M)
        if m:
            return int(m.group(1))
    return CODEX_PROJECT_DOC_DEFAULT_BYTES


def agents_bytes(root: Path = ROOT) -> tuple[int, int]:
    """(size of AGENTS.md in bytes, the Codex limit it must stay under)."""
    path = root / "AGENTS.md"
    size = path.stat().st_size if path.is_file() else 0
    return size, codex_project_doc_limit(root)


def check_agents_bytes() -> None:
    size, limit = agents_bytes()
    hint = f"raise project_doc_max_bytes in {CODEX_CONFIG} or move procedure out into skills"
    if size >= limit:
        report("error", "AGENTS.md",
               f"{size} bytes, at or over Codex's project_doc_max_bytes={limit} — the tail of the "
               f"file (the team rules) is silently dropped; {hint}")
    elif size > limit * AGENTS_BYTES_WARN_RATIO:
        report("warn", "AGENTS.md",
               f"{size} bytes of Codex's project_doc_max_bytes={limit} — {hint} before it is cut")


def check_crossdoc() -> None:
    """A command that exists but is documented nowhere is a command nobody runs,
    and every agent here works from the docs rather than from --help."""
    for rel, lines, budget in agent_budget_violations():
        report("warn", rel,
               f"{lines} lines (budget ~{budget}) — keep routing and policy here; move procedures to skills")
    check_agents_bytes()

    wt = (ROOT / "agents/common/skills/wt/wt").read_text()

    dispatch = re.search(r"\ncase \"\$cmd\" in\n(.*?)\nesac", wt, re.S)
    if not dispatch:
        report("warn", "agents/common/skills/wt/wt", "cannot find the subcommand dispatch block — crossdoc check skipped")
    else:
        subs = re.findall(r"^\s*([a-z-]+)\)\s*cmd_", dispatch.group(1), re.M)
        usage = re.search(r"sed \"s\|@SELF@\|\$SELF\|g\" <<'EOF'\n(.*?)\nEOF", wt, re.S)
        usage_text = usage.group(1) if usage else ""
        worktrees_md = (ROOT / "WORKTREES.md").read_text()
        for s in subs:
            if not re.search(rf"^\s*wt {s}\b", usage_text, re.M):
                report("error", "agents/common/skills/wt/wt",
                       f"subcommand '{s}' is dispatched but absent from usage()")
            if not re.search(rf"\bwt {s}\b", worktrees_md):
                report("error", "WORKTREES.md",
                       f"subcommand '{s}' exists in wt but is not documented here")

    # A skill nobody names is a skill nobody invokes. Engine skills are named
    # in AGENTS.md, module skills in the module README — so the check is
    # against all of them at once.
    prose = (ROOT / "AGENTS.md").read_text()
    for extra in ("WORKTREES.md", "GIT.md"):
        f = ROOT / extra
        if f.is_file():
            prose += f.read_text()
    if (CLAUDE / "skills").is_dir():
        for d in sorted(p for p in (CLAUDE / "skills").iterdir() if p.is_dir()):
            # A skill imported from packages/ (repos.json `skills`) is documented
            # by its own repository; its link resolves outside agents/.
            if not d.resolve().is_relative_to((ROOT / "agents").resolve()):
                continue
            if f"`{d.name}`" not in prose:
                report("warn", "AGENTS.md",
                       f"skill '{d.name}' exists but is named in no doc — agents find skills through these")

    # AGENTS.md sends every agent to PACKAGES.md to decide which repo a task
    # belongs in, and repo names are routinely similar. A repo in the manifest
    # with no row there is a repo nobody can place.
    manifest_path = ROOT / "repos.json"
    packages_path = ROOT / "PACKAGES.md"
    if manifest_path.is_file() and packages_path.is_file():
        manifest = json.loads(manifest_path.read_text())
        packages_md = packages_path.read_text()
        for repo in sorted(manifest.get("repos", {})):
            if f"`{repo}`" not in packages_md:
                report("warn", str(packages_path.relative_to(ROOT)),
                       f"repo '{repo}' is in the manifest but has no entry here")


# ------------------------------------------------------- context scanner ---

# Some deployed agent runtimes scan every context file and every skill before
# it enters the system prompt, and a match does not warn — it replaces the
# ENTIRE file with "[BLOCKED: <file> contained potential prompt injection
# (<rule>). Content not loaded.]". One offending line in AGENTS.md therefore
# costs the whole ruleset, with a single log line as the only trace. There is
# no allowlist and no way to switch it off on that side.
#
# These three are the upstream "all"-scope rules that ordinary documentation
# can plausibly trip, originally mirrored from a context-scanning agent
# runtime's threat_patterns.py and compiled case-insensitively there too (that
# runtime is no longer part of this workspace, but the check is kept as a
# general safeguard against credential lines in tracked docs and skills). A
# mirror can drift when upstream adds a rule; the failure mode of drift is this
# check missing something, never blocking something correct, which is the
# right direction.
#
# The fix is never to delete the example. It is to keep the credential off the
# same LINE as the command — these patterns are single-line — usually by
# assigning the header to a variable first. AGENTS.md's credentials section
# shows the shape.
SCANNER_RULES = [
    (re.compile(r"curl\s+[^\n]{0,2048}\$\{?\w*(KEY|TOKEN|SECRET|PASSWORD|CREDENTIAL|API)", re.I),
     "exfil_curl"),
    (re.compile(r"wget\s+[^\n]{0,2048}\$\{?\w*(KEY|TOKEN|SECRET|PASSWORD|CREDENTIAL|API)", re.I),
     "exfil_wget"),
    (re.compile(r"cat\s+[^\n]{0,2048}(\.env|credentials|\.netrc|\.pgpass|\.npmrc|\.pypirc)", re.I),
     "read_secrets"),
]


def check_scanner(files: list[Path]) -> None:
    """No tracked doc or skill trips a context-scanning agent runtime's rules."""
    for f in files:
        for lineno, line in enumerate(f.read_text().split("\n"), 1):
            for pat, rule in SCANNER_RULES:
                if pat.search(line):
                    report("error", f"{f.relative_to(ROOT)}:{lineno}",
                           f"a context scanner would reject this file whole "
                           f"({rule}) and load none of it — keep the credential off "
                           f"the same line as the command")


# --------------------------------------------------------------------- main ---

CHECKS = {
    "skills": lambda md: check_skills(),
    "links": check_links,
    "paths": check_paths,
    "fences": check_fences,
    "forbidden": check_forbidden,
    "crossdoc": lambda md: check_crossdoc(),
    "scanner": check_scanner,
}


def main() -> int:
    ap = argparse.ArgumentParser(description="Markdown and skill-contract checks for the harness.")
    ap.add_argument("--only", action="append", choices=sorted(CHECKS), help="run just these checks")
    ap.add_argument("--strict", action="store_true", help="treat warnings as errors")
    args = ap.parse_args()

    md = [f for f in tracked("*.md") if f.exists()]
    for name in (args.only or sorted(CHECKS)):
        CHECKS[name](md)

    errors = [f for f in findings if f[0] == "error"]
    warns = [f for f in findings if f[0] == "warn"]

    for sev, loc, msg in sorted(findings, key=lambda f: (f[0] != "error", f[1])):
        label = "error" if sev == "error" else "warn "
        print(f"  {label}  {loc}: {msg}")

    if not findings:
        print("  clean")

    if errors or (warns and args.strict):
        return 1
    return 0


if __name__ == "__main__":
    os.chdir(ROOT)
    sys.exit(main())
